// Connect Pro Fleet — system role default permissions (Build #5+).
// Extracted from permissions.ts to keep it under the line limit. The role
// defaults reference PERMISSION_KEYS (built from PERMISSION_CATALOG) so new
// permissions automatically default to false for non-owner roles.
//
// To avoid a circular import (permissions.ts imports SYSTEM_ROLE_PERMISSIONS
// from here, and we need the permission keys), we import PERMISSION_CATALOG
// from the catalog module (no cycle) and derive the keys locally.

import { PERMISSION_CATALOG } from "./permissionCatalog";

const PERMISSION_KEYS = PERMISSION_CATALOG.map((p) => p.key);

function allTrue(): Record<string, boolean> {
  return Object.fromEntries(PERMISSION_KEYS.map((k) => [k, true]));
}

function pick(keys: string[]): Record<string, boolean> {
  return Object.fromEntries(PERMISSION_KEYS.map((k) => [k, keys.includes(k)]));
}

