function snap(
  over: Partial<ReservationPricingSnapshot>,
): ReservationPricingSnapshot {
  return {
    vehicle_class_id: null,
    vehicle_class_name: null,
    daily_rate: 0,
    weekly_rate: 0,
    minimum_rental_duration: 1,
    duration_days: 7,
    recommended_total: 0,
    recommended_rate_type: "weekly",
    components: [],
    ...over,
  };
}

function weeklyCfg(rate: number, anchor: string): RentalBillingConfig {
  return {
    billing_frequency: "weekly",
    billing_anchor_date: anchor,
    recurring_amount: rate,
    auto_generate_periods: true,
    custom_schedule: null,
  };
}

function upfrontCfg(anchor: string): RentalBillingConfig {
  return {
    billing_frequency: "upfront",
    billing_anchor_date: anchor,
    recurring_amount: null,
    auto_generate_periods: true,
    custom_schedule: null,
  };
}

function biweeklyCfg(rate: number, anchor: string): RentalBillingConfig {
  return {
    billing_frequency: "biweekly",
    billing_anchor_date: anchor,
    recurring_amount: rate,
    auto_generate_periods: true,
    custom_schedule: null,
  };
}

