/** A captured digital signature on a generated record (spec §13). */
export interface VaultSignature {
  role: "buyer" | "seller" | "recorder";
  signer_name: string;
  signature_data: string; // typed text or stroke data URI
  signed_at: string; // ISO timestamp
  staff_id: string | null;
}

/** Relationship target — a vault document links to at most one authoritative
 *  record per type (spec §32). Multiple link types may coexist. */
export interface VaultDocLinks {
  expense_id: string | null;
  acquisition_vehicle_id: string | null;
  work_order_id: string | null;
  damage_claim_id: string | null;
  incident_id: string | null;
  violation_id: string | null;
}

/** A vault document. Uploaded files and generated records share this shape so
 *  the vault table is uniform. Generated records carry extra fields. */
export interface VaultDocument {
  id: string;
  tenant_id: string;
  vehicle_id: string;
  kind: VaultDocKind;
  category: VaultDocCategory;
  group: VaultDocGroup;
  document_number: string; // tenant-scoped, immutable (spec §30/§31)
  version: number; // 1-based; amendments increment (spec §44)
  title: string;
  description: string | null;
  // File reference (uploaded/scanned). Null for generated-only records.
  file_name: string | null;
  file_url: string | null;
  mime_type: string | null;
  // Vendor / seller
  vendor_name: string | null;
  vendor_phone: string | null;
  vendor_email: string | null;
  vendor_address: string | null;
  // Amount (optional — not every document has a dollar value)
  amount: number | null;
  expense_date: string | null; // date the spend/purchase occurred
  // Cash-expense-specific
  payment_method: TenderMethod | null;
  expense_category_id: string | null;
  notes: string | null;
  // Purchase / bill-of-sale-specific
  seller_name: string | null;
  seller_address: string | null;
  seller_phone: string | null;
  seller_email: string | null;
  purchase_date: string | null;
  purchase_price: number | null;
  purchase_payment_method: string | null;
  odometer: number | null;
  terms: string | null;
  as_is: boolean;
  source_platform: string | null; // "Facebook Marketplace", etc.
  is_internal: boolean; // true for Internal Purchase Record (not seller-signed)
  // Lifecycle
  status: VaultDocStatus;
  source: VaultDocSource;
  signatures: VaultSignature[];
  links: VaultDocLinks;
  supersedes_doc_id: string | null; // amendment chain (spec §44)
  superseded_by_doc_id: string | null;
  void_reason: string | null;
  created_by: string | null; // staff id
  created_at: string;
  updated_at: string;
}

