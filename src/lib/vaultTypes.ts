// Connect Pro Fleet — Vehicle Document Vault types (Build #45).
//
// The Vault is a permanent document trail for every meaningful vehicle expense
// or ownership event — even when no traditional receipt exists. A VaultDocument
// is SUPPORTING EVIDENCE. It may link to an authoritative Expense Ledger entry
// or a Vehicle Acquisition record, but it is NOT itself a financial record and
// does NOT duplicate the Expense Ledger or the vehicle purchase_price field.
//
// Generated records (Cash Expense Record, Bill of Sale, Internal Purchase
// Record) are clearly labelled as generated business documentation — never as
// original vendor receipts, and never as legal/tax guarantees.

import type { TenderMethod } from "./paymentMethodTypes";

