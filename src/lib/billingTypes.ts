// Connect Pro Fleet — Universal rental billing domain types (Build #3).
//
// Separates three concepts that were previously conflated:
//   RENTAL TERM     — how long the customer rents (rental dates)
//   RATE TYPE       — how the price was calculated (daily / weekly / mixed / custom)
//   BILLING SCHEDULE — when the customer owes money (upfront / daily / weekly / ...)
//
// The FinancialTransaction ledger remains the financial source of truth.
// A BillingPeriod is schedule/obligation context — it never holds a competing
// balance. Period paid/balance values are DERIVED from the ledger via FIFO
// allocation (see billing.ts). types.ts re-exports these for compatibility.

import type { RateType } from "./types";

/**
 * How often a rental bills the customer. Independent of rate type: a daily-
 * priced rental can bill upfront, and a custom-priced 30-day rental can bill
 * weekly installments.
 *
 * `monthly` is reserved for future structural compatibility only — no monthly
 * workflow is built in this phase.
 */
export type BillingFrequency =
  "upfront" | "daily" | "weekly" | "biweekly" | "custom" | "monthly";

/** Lifecycle of a single billing obligation. Derived from due date + ledger. */
export type BillingPeriodStatus =
  | "upcoming"
  | "due"
  | "partially_paid"
  | "paid"
  | "past_due"
  | "waived"
  | "cancelled";

/** How a BillingPeriod record came to exist. */
export type BillingPeriodSource =
  | "engine" // generated by the billing processing engine
  | "manual" // staff added a one-off obligation
  | "custom_schedule" // part of a manually defined payment schedule
  | "migrated"; // backfilled from a historical ledger charge (non-destructive)

/**
 * A single rental billing obligation — one period that is billed and becomes
 * due. The ledger charge backing it is linked via `transaction_id`; payments
 * are allocated FIFO across a rental's periods (see billing.ts).
 */
export interface BillingPeriod {
  id: string;
  tenant_id: string;
  rental_id: string;
  /** Invoice that organizes this period's charges, if any. */
  invoice_id: string | null;
  /** 1-based sequence within the rental (chronological). */
  sequence_number: number;
  period_start: string; // ISO date (inclusive)
  period_end: string; // ISO date (inclusive)
  /** When this obligation becomes due. */
  due_at: string; // ISO date
  billing_frequency: BillingFrequency;
  rate_type: RateType;
  /** Scheduled base rental charge for this period. */
  base_amount: number;
  /** Add-ons / fees scheduled for this period. */
  additional_amount: number;
  tax_amount: number;
  fee_amount: number;
  /** Scheduled total obligation for this period (base + additional + tax + fees). */
  total_amount: number;
  status: BillingPeriodStatus;
  generated_at: string;
  /** When the period was fully satisfied (derived), if applicable. */
  paid_at: string | null;
  /** Stable dedupe identity: `${rental_id}|${period_start}|${period_end}`. */
  dedupe_key: string;
  source: BillingPeriodSource;
  /** Ledger charge backing this period (the base rental charge). */
  transaction_id: string | null;
  /** Ledger charge IDs for per-period fees (linked via metadata.billing_period_id). */
  fee_transaction_ids: string[];
  /** Ledger charge IDs for per-period taxes. */
  tax_transaction_ids: string[];
  /** True once a late fee has been posted against this period (dedupe). */
  late_fee_applied: boolean;
  created_at: string;
  updated_at: string;
}

/**
 * A manually-defined installment for a custom billing schedule.
 * Belongs to the original rental billing agreement (not the future Payment
 * Arrangements feature, which handles overdue balances/promises).
 */
export interface CustomScheduleInstallment {
  due_at: string; // ISO date
  amount: number;
  label?: string;
}

/**
 * Billing configuration stored on a rental, separate from its rental dates.
 * Optional fields keep existing weekly rentals working without changes; the
 * engine backfills/migrates them on first processing.
 */
export interface RentalBillingConfig {
  billing_frequency: BillingFrequency;
  /** Anchor date periods are measured from (defaults to checkout/pickup date). */
  billing_anchor_date: string | null;
  /** Agreed recurring payment amount. Stored, not re-derived from class price. */
  recurring_amount: number | null;
  /** Auto-generate periods as they become due (default true). */
  auto_generate_periods: boolean;
  /** Custom schedule installments (only when frequency === "custom"). */
  custom_schedule: CustomScheduleInstallment[] | null;
}

